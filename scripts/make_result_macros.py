#!/usr/bin/env python3
"""Generate LaTeX result macros and the selected-rate interval table."""

from __future__ import annotations

import argparse
import shutil
import sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from make_false_adequacy_rates import _wilson_interval  # noqa: E402


SCENARIO_PREFIX = {
    "clean_null": "Anchor",
    "injected_residual": "Injected",
    "leakage": "Leakage",
    "selection_standard": "Selection",
    "collider_selection": "Collider",
    "adversarial_null": "Adversarial",
    "opposite_direction": "Opposite",
}

OUTCOMES = {
    "Support": ("support_n", "support_rate"),
    "Adequate": ("null_n", "null_rate"),
    "SelectionLimited": (
        "selection_limited_n",
        "selection_limited_rate",
    ),
    "DiagnosticFailure": (
        "diagnostic_failure_n",
        "diagnostic_failure_rate",
    ),
    "OppositeDirection": (
        "opposite_direction_n",
        "opposite_direction_rate",
    ),
    "Inconclusive": ("inconclusive_n", "inconclusive_rate"),
}


def _atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def _macro(name: str, value: str) -> str:
    return f"\\providecommand{{\\{name}}}{{{value}}}"


def _count_from_rate(row, rate_column: str) -> int:
    return int(round(int(row["M"]) * float(row[rate_column])))


def _rate3_from_count(n: int, m: int) -> str:
    rate = (Decimal(n) / Decimal(m)).quantize(
        Decimal("0.001"), rounding=ROUND_HALF_UP
    )
    return f"{rate:.3f}"


def _build_macros(
    run_hash: str,
    oc: pd.DataFrame,
    adequacy: pd.DataFrame,
    route_contrasts: pd.DataFrame | None = None,
) -> str:
    indexed = oc.set_index("scenario")
    m_values = set(oc["M"].astype(int))
    if len(m_values) != 1:
        raise ValueError("canonical scenarios do not share one M")
    m = m_values.pop()
    lines = [
        "% Machine-generated by scripts/make_result_macros.py; do not edit.",
        _macro("LevelIIARunHashRaw", run_hash),
        _macro(
            "LevelIIARunHash",
            "\\texttt{\\LevelIIARunHashRaw}",
        ),
        _macro(
            "LevelIIAOutputRoot",
            "\\texttt{outputs/\\LevelIIARunHashRaw}",
        ),
        _macro("LevelIIAM", str(m)),
    ]

    for scenario, prefix in SCENARIO_PREFIX.items():
        row = indexed.loc[scenario]
        for label, (n_column, rate_column) in OUTCOMES.items():
            n = int(row[n_column])
            rate_text = _rate3_from_count(n, m)
            lines.append(_macro(f"LevelIIA{prefix}{label}N", str(n)))
            lines.append(
                _macro(f"LevelIIA{prefix}{label}Rate", rate_text)
            )
            lines.append(
                _macro(
                    f"LevelIIA{prefix}{label}CountRate",
                    f"{n}/{m}={rate_text}",
                )
            )

        nonaffirmation = m - int(row["null_n"])
        lines.append(
            _macro(
                f"LevelIIA{prefix}NonaffirmationN",
                str(nonaffirmation),
            )
        )
        if scenario == "clean_null":
            lines.append(
                _macro(
                    "LevelIIAAnchorNonaffirmationCountRate",
                    f"{nonaffirmation}/{m}={_rate3_from_count(nonaffirmation, m)}",
                )
            )
        for label, column in [
            ("LeakFire", "leak_fire_rate"),
            ("RetentionFire", "retention_fire_rate"),
            ("ColliderInterFire", "collider_inter_fire_rate"),
            ("ColliderFire", "collider_fire_rate"),
        ]:
            rate = float(row[column])
            n = _count_from_rate(row, column)
            lines.append(_macro(f"LevelIIA{prefix}{label}N", str(n)))
            lines.append(_macro(f"LevelIIA{prefix}{label}Rate", f"{rate:.3f}"))
        lines.append(
            _macro(
                f"LevelIIA{prefix}BetaMinMedian",
                f"{float(row['beta_min_med']):.3f}",
            )
        )

    family_sizes = set(adequacy["route"].astype(str))
    directions = set(adequacy["direction"].astype(str))
    family_size = len(adequacy)
    adequacy_ids = set(adequacy["adequacy_id"].astype(str))
    if len(adequacy_ids) != 1:
        raise ValueError("adequacy rows do not share one adequacy_id")
    lines.append(
        _macro("LevelIIAAdequacyIdRaw", adequacy_ids.pop())
    )
    lines.append(_macro("LevelIIAAdequacyFamilySize", str(family_size)))
    lines.append(
        _macro(
            "LevelIIAAdequacyPFaMax",
            f"{float(adequacy['p_fa_max'].iloc[0]):.3f}",
        )
    )
    grid = sorted(set(float(x) for x in adequacy["delta"]))
    lines.append(
        _macro(
            "LevelIIAAdequacyGrid",
            ",".join(f"{x:g}" for x in grid),
        )
    )
    lines.append(
        _macro(
            "LevelIIAAdequacyGridDisplay",
            ", ".join(f"{x:g}" for x in grid),
        )
    )

    route_prefix = {
        "assignment_isolation": "AssignmentIsolation",
        "sequential_evalue": "Sequential",
    }
    direction_prefix = {"negative": "Negative", "positive": "Positive"}
    for route in sorted(family_sizes):
        for direction in sorted(directions):
            group = adequacy[
                (adequacy["route"] == route)
                & (adequacy["direction"] == direction)
            ].sort_values("delta")
            values = group["certified_delta_direction"].dropna().unique()
            delta_star = "not-certified" if len(values) == 0 else f"{float(values[0]):g}"
            prefix = route_prefix[route] + direction_prefix[direction]
            lines.append(
                _macro(
                    f"LevelIIA{prefix}CertifiedDelta",
                    delta_star,
                )
            )
            censored = bool(group["lower_grid_censored"].astype(bool).any())
            lines.append(
                _macro(
                    f"LevelIIA{prefix}LowerGridCensored",
                    "yes" if censored else "no",
                )
            )
            at_sixty = group[group["delta"] == 60.0]
            if len(at_sixty) == 1:
                row = at_sixty.iloc[0]
                lines.append(
                    _macro(
                        f"LevelIIA{prefix}SixtyFalseAdequacyCountRate",
                        (
                            f"{int(row['false_adequacy_n'])}/{int(row['M'])}"
                            f"={float(row['false_adequacy_rate']):.3f}"
                        ),
                    )
                )
                lines.append(
                    _macro(
                        f"LevelIIA{prefix}SixtySimultaneousUpper",
                        f"{float(row['simultaneous_cp_upper']):.6f}",
                    )
                )
    # Route-level summary macros are emitted only after asserting that the
    # negative- and positive-direction certificates agree. This prevents prose
    # from silently claiming a common boundary after a future recertification in
    # which the two directions diverge.
    for route, route_name in route_prefix.items():
        route_rows = adequacy[adequacy["route"] == route]
        certified = {}
        for direction in sorted(directions):
            values = (
                route_rows.loc[
                    route_rows["direction"] == direction,
                    "certified_delta_direction",
                ]
                .dropna()
                .unique()
            )
            certified[direction] = None if len(values) == 0 else float(values[0])
        if certified.get("negative") != certified.get("positive"):
            raise ValueError(
                f"{route}: directional certified deltas differ: {certified}"
            )
        common = certified.get("negative")
        common_text = "not-certified" if common is None else f"{common:g}"
        lines.append(
            _macro(
                f"LevelIIA{route_name}CertifiedDeltaBothDirections",
                common_text,
            )
        )

    # Manuscript-facing sequential 20-unit false-adequacy rates.
    for direction, direction_name in direction_prefix.items():
        row20 = adequacy[
            (adequacy["route"] == "sequential_evalue")
            & (adequacy["direction"] == direction)
            & (adequacy["delta"] == 20.0)
        ]
        if len(row20) != 1:
            raise ValueError(
                f"expected one sequential 20-unit cell for {direction}"
            )
        row20 = row20.iloc[0]
        lines.append(
            _macro(
                f"LevelIIASequential{direction_name}TwentyFalseAdequacyRate",
                f"{float(row20['false_adequacy_rate']):.3f}",
            )
        )

    # The displayed ±60 summary is a shared statement across both routes and
    # directions. Emit it only after asserting equality of all four cells.
    sixty = adequacy[adequacy["delta"] == 60.0]
    if len(sixty) != 4:
        raise ValueError("expected four route-by-direction cells at delta=60")
    sixty_counts = set(sixty["false_adequacy_n"].astype(int))
    sixty_m = set(sixty["M"].astype(int))
    sixty_rates = {round(float(x), 12) for x in sixty["false_adequacy_rate"]}
    sixty_upper = {round(float(x), 12) for x in sixty["simultaneous_cp_upper"]}
    if not (
        len(sixty_counts) == 1
        and len(sixty_m) == 1
        and len(sixty_rates) == 1
        and len(sixty_upper) == 1
    ):
        raise ValueError("delta=60 cells do not share one manuscript summary")
    sixty_n = next(iter(sixty_counts))
    sixty_m_value = next(iter(sixty_m))
    sixty_rate = next(iter(sixty_rates))
    sixty_upper_value = next(iter(sixty_upper))
    lines.append(
        _macro(
            "LevelIIASixtyFalseAdequacyCountRate",
            f"{sixty_n}/{sixty_m_value}={sixty_rate:.3f}",
        )
    )
    lines.append(
        _macro(
            "LevelIIASixtySimultaneousUpperDisplay",
            f"{sixty_upper_value:.4f}",
        )
    )

    # Route-matched contrasts are a separate frozen summary object. When present,
    # expose their manuscript repetitions as macros rather than hand-typed prose.
    if route_contrasts is not None:
        expected = {
            "clean_sequential_minus_clean_assignment":
                "CleanSequentialMinusAssignment",
            "adversarial_sequential_minus_clean_sequential":
                "AdversarialSequentialMinusCleanSequential",
        }
        indexed_contrasts = route_contrasts.set_index("contrast_id")
        missing = sorted(set(expected) - set(indexed_contrasts.index.astype(str)))
        if missing:
            raise ValueError(f"missing route-matched contrasts: {missing}")
        for contrast_id, macro_prefix in expected.items():
            row = indexed_contrasts.loc[contrast_id]
            lines.append(
                _macro(
                    f"LevelIIA{macro_prefix}Estimate",
                    f"{float(row['estimate']):+.3f}",
                )
            )
            lines.append(
                _macro(
                    f"LevelIIA{macro_prefix}Interval",
                    f"[{float(row['ci95_low']):+.3f}, {float(row['ci95_high']):+.3f}]",
                )
            )

    return "\n".join(lines) + "\n"


def _build_interval_table(run_hash: str, oc: pd.DataFrame) -> str:
    indexed = oc.set_index("scenario")
    specifications = [
        ("Anchor support", "clean_null", "support_n"),
        ("Adversarial-null support", "adversarial_null", "support_n"),
        ("Injected-residual support", "injected_residual", "support_n"),
        (
            "Injected-residual false adequacy",
            "injected_residual",
            "null_n",
        ),
        ("Leakage audit fire", "leakage", "leak_fire_rate"),
        (
            "Standard-selection retention audit fire",
            "selection_standard",
            "retention_fire_rate",
        ),
        (
            "Standard-selection selection-limited classification",
            "selection_standard",
            "selection_limited_n",
        ),
        (
            "Collider diagnostic fire",
            "collider_selection",
            "collider_fire_rate",
        ),
        (
            "Collider selection-limited classification",
            "collider_selection",
            "selection_limited_n",
        ),
        (
            "Opposite-direction classification",
            "opposite_direction",
            "opposite_direction_n",
        ),
        (
            "Opposite-direction false adequacy",
            "opposite_direction",
            "null_n",
        ),
    ]
    lines = [
        "% Machine-generated by scripts/make_result_macros.py; do not edit.",
        f"% Source run: {run_hash}",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Selected realised operating rates with pointwise Wilson 95\\% intervals.}",
        "\\label{tab:si-oc-intervals}",
        "\\footnotesize",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Rate & Count & Estimate & Wilson 95\\% interval \\\\",
        "\\midrule",
    ]
    for label, scenario, field in specifications:
        row = indexed.loc[scenario]
        m = int(row["M"])
        if field.endswith("_n"):
            n = int(row[field])
        else:
            n = _count_from_rate(row, field)
        rate = n / m
        low, high = _wilson_interval(n, m)
        lines.append(
            f"{label} & {n}/{m} & {rate:.3f} & "
            f"[{low:.3f},{high:.3f}] \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-hash", required=True)
    parser.add_argument("--outdir", default=str(ROOT / "outputs"))
    parser.add_argument("--no-copy", action="store_true")
    args = parser.parse_args()

    run_dir = Path(args.outdir).resolve() / args.run_hash
    oc = pd.read_csv(
        run_dir / "summary" / "operating_characteristics.csv"
    )
    adequacy = pd.read_csv(
        run_dir / "summary" / "adequacy_operating_characteristic.csv"
    )
    route_contrasts_path = (
        run_dir / "summary" / "route_matched_null_contrasts.csv"
    )
    route_contrasts = (
        pd.read_csv(route_contrasts_path)
        if route_contrasts_path.exists()
        else None
    )
    macro_path = run_dir / "tables" / "v12_result_macros.tex"
    interval_path = (
        run_dir / "tables" / "operating_characteristics_intervals.tex"
    )
    _atomic(
        macro_path,
        _build_macros(
            args.run_hash,
            oc,
            adequacy,
            route_contrasts=route_contrasts,
        ),
    )
    _atomic(interval_path, _build_interval_table(args.run_hash, oc))

    if not args.no_copy:
        destination = ROOT / "manuscript" / "tables"
        destination.mkdir(parents=True, exist_ok=True)
        shutil.copy2(macro_path, destination / macro_path.name)
        shutil.copy2(interval_path, destination / interval_path.name)

    print(f"[result-macros] wrote {macro_path}")
    print(f"[result-macros] wrote {interval_path}")


if __name__ == "__main__":
    main()
